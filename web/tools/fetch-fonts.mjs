// Self-host the two brand fonts from Google Fonts.
// Usage: node tools/fetch-fonts.mjs   (run from /web)
import { mkdir, writeFile } from "node:fs/promises";
import { createHash } from "node:crypto";
import path from "node:path";

const UA =
  "Mozilla/5.0 (Windows NT 10.0; Win64; x64) AppleWebKit/537.36 (KHTML, like Gecko) Chrome/124.0 Safari/537.36";
const FAMILIES = [
  "Be+Vietnam+Pro:wght@400;500;600;700",
  "JetBrains+Mono:wght@400;500",
];
const KEEP = /(latin|vietnamese)/;
const OUT = path.resolve("assets/fonts");

await mkdir(OUT, { recursive: true });

let out = `/* Generated by tools/fetch-fonts.mjs — do not edit by hand. */\n`;
const seen = new Set();

for (const family of FAMILIES) {
  const url = `https://fonts.googleapis.com/css2?family=${family}&display=swap`;
  const css = await fetch(url, { headers: { "User-Agent": UA } }).then((r) => r.text());
  const blocks = css.split(/(?=@font-face)/g).filter((b) => b.includes("@font-face"));

  for (const block of blocks) {
    const subset = (block.match(/\/\*\s*([a-z-]+)\s*\*\//) || [])[1] || "latin";
    if (!KEEP.test(subset)) continue;
    const src = block.match(/url\((https:[^)]+\.woff2)\)/);
    if (!src) continue;
    const remote = src[1];
    const hash = createHash("sha1").update(remote).digest("hex").slice(0, 8);
    const name = `font-${hash}.woff2`;
    const file = path.join(OUT, name);
    if (!seen.has(remote)) {
      const buf = Buffer.from(await fetch(remote).then((r) => r.arrayBuffer()));
      await writeFile(file, buf);
      seen.add(remote);
      console.log(`${name}  ${(buf.length / 1024).toFixed(1)} KB  ${subset}`);
    }
    out += block.replace(/url\(https:[^)]+\.woff2\)/, `url(./fonts/${name})`).trim() + "\n";
  }
}

await writeFile(path.resolve("assets/fonts.css"), out);
console.log(`\nWrote assets/fonts.css with ${seen.size} font files.`);
